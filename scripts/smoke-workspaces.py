#!/usr/bin/env python3
"""Verify file-parent defaults and ws exclusion/release across independent CLI processes."""
import json
from pathlib import Path
import signal
import subprocess
import time
import uuid

ROOT = Path(__file__).resolve().parents[1]
CLI = ROOT / 'cli/build/install/jenkinsfile-exec/bin/jenkinsfile-exec'
work = ROOT / 'build' / ('workspace-smoke-' + uuid.uuid4().hex[:8])
shared = work / 'shared'
work.mkdir(parents=True)


def make_case(name, body):
    directory = work / name
    directory.mkdir()
    script = directory / 'Jenkinsfile'
    script.write_text("pipeline { agent any; stages { stage('ws') { steps { script {\n" + body + "\n} } } } }")
    return script


def groovy_string(path):
    # These paths are generated by this test, but still quote a literal safely.
    return "'" + str(path).replace('\\', '\\\\').replace("'", "\\'") + "'"


first = make_case('holder', 'ws(' + groovy_string(shared) + ") {\nwriteFile file:'holding',text:pwd()\nsh 'sleep 30'\n}")
second = make_case('contender', 'def base=pwd()\nws(' + groovy_string(shared) + ") {\nwriteFile file:base+'/selected',text:pwd()\nassert env.WORKSPACE==pwd()\n}")
third = make_case('reuse', 'def base=pwd()\nws(' + groovy_string(shared) + ") {writeFile file:base+'/selected',text:pwd()}\nassert pwd()==base")

with (work / 'holder.log').open('w') as log:
    holder = subprocess.Popen([str(CLI), 'run', str(first)], cwd=ROOT, stdout=log, stderr=subprocess.STDOUT)
    try:
        deadline = time.monotonic() + 15
        while not (shared / 'holding').exists():
            if holder.poll() is not None or time.monotonic() > deadline:
                raise RuntimeError('First workspace was not acquired: ' + str(work / 'holder.log'))
            time.sleep(0.05)
        # No --workspace is passed: each Jenkinsfile's parent must receive its report/results.
        with (work / 'contender.log').open('w') as output:
            subprocess.run([str(CLI), 'run', str(second)], cwd=ROOT, stdout=output, stderr=subprocess.STDOUT, timeout=15, check=True)
        assert second.parent.joinpath('selected').read_text() == str(shared) + '@2'
        assert list(second.parent.joinpath('.local-jenkinsfile/runs').glob('*.json'))
        holder.send_signal(signal.SIGINT)
        assert holder.wait(timeout=6) == 130
        with (work / 'reuse.log').open('w') as output:
            subprocess.run([str(CLI), 'run', str(third)], cwd=ROOT, stdout=output, stderr=subprocess.STDOUT, timeout=15, check=True)
        assert third.parent.joinpath('selected').read_text() == str(shared)
        print('PASS: Jenkinsfile-parent defaults, cross-process @2 exclusion, and release after SIGINT. Evidence: ' + str(work))
    finally:
        if holder.poll() is None:
            holder.send_signal(signal.SIGINT)
            try:
                holder.wait(timeout=6)
            except subprocess.TimeoutExpired:
                holder.kill()
                holder.wait()
